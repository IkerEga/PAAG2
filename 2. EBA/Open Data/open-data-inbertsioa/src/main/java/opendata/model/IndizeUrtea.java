package opendata.model;

public class IndizeUrtea {
    private final int urtea;
    private final double balioa;

    public IndizeUrtea(int urtea, double balioa) {
        this.urtea = urtea;
        this.balioa = balioa;
    }

    public int getUrtea() { return urtea; }
    public double getBalioa() { return balioa; }
    
}
